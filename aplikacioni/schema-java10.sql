DO $migration$
DECLARE
  udhetim_id_type TEXT;
BEGIN
  SELECT format_type(a.atttypid, a.atttypmod)
  INTO udhetim_id_type
  FROM pg_attribute a
  WHERE a.attrelid = 'public.udhetimet'::regclass
    AND a.attname = 'id'
    AND a.attnum > 0
    AND NOT a.attisdropped;

  IF udhetim_id_type IS NULL THEN
    RAISE EXCEPTION 'Nuk u gjet kolona public.udhetimet.id.';
  END IF;

  EXECUTE format(
    'CREATE TABLE IF NOT EXISTS public.te_preferuarat (
      github_id TEXT NOT NULL REFERENCES public.profilet(github_id),
      udhetimi_id %s NOT NULL REFERENCES public.udhetimet(id),
      krijuar_me TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      PRIMARY KEY (github_id, udhetimi_id)
    )',
    udhetim_id_type
  );

  EXECUTE format(
    'CREATE TABLE IF NOT EXISTS public.kerkesat_udhetimit (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      udhetim_id %s NOT NULL REFERENCES public.udhetimet(id),
      udhetar_id TEXT NOT NULL REFERENCES public.profilet(github_id),
      status TEXT NOT NULL DEFAULT ''ne pritje''
        CHECK (status IN (''ne pritje'', ''e pranuar'')),
      krijuar_me TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      pranuar_me TIMESTAMPTZ,
      UNIQUE (udhetim_id, udhetar_id),
      CHECK (
        (status = ''ne pritje'' AND pranuar_me IS NULL)
        OR (status = ''e pranuar'' AND pranuar_me IS NOT NULL)
      )
    )',
    udhetim_id_type
  );
END
$migration$;

CREATE INDEX IF NOT EXISTS kerkesat_udhetimit_udhetim_status_idx
  ON kerkesat_udhetimit (udhetim_id, status);
